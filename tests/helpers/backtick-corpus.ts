/**
 * **從測試檔裡撈反引號片段**——七支護欄與探針共用的那一步。
 *
 * ## 🔴 為什麼要抽出來：長度上限寫在正則裡會【生出幽靈語料】
 *
 * 七處原本各自寫著 `` /`([^`]{4,400})`/g ``。那個 `{4,400}` 看起來只是
 * 「太長的不要」，而它真正做的事是：
 *
 * ```
 * 一段超過 400 字的樣板字串 → 【配不到對】
 *   → 它的收尾反引號改跟【下一段的開頭反引號】配
 *   → 夾在中間的【測試程式碼本身】被當成一段 C++ 語料撈走
 * ```
 *
 * 症狀是那些幽靈段以 `")` 之類的東西開頭——`expect(interp.getOutput()…`。
 *
 * **2026-08-26 實測**：`tests/integration/` 下
 *
 * ```
 * 配對錯位（原本）  1078 段
 * 配對正確          907 段
 * 🔴 幽靈            171 段（16%）
 * ```
 *
 * ⚠️ 而它的代價**不是「漏掉長的那些」，是「無中生有」**——那 171 段全部
 * 落進「語法有錯（片段）」欄，於是那一欄看起來像「語料裡本來就有很多片段」。
 *
 * > **一個把上限寫進配對規則裡的掃描器，
 * > 不會少給你東西，它會給你不存在的東西。**
 *
 * 這正是 [`build-guardrail` §6.5](../../knowledge/skills/build-guardrail/SKILL.md)
 * 「紅的是世界，還是語料」那一節在講的事——而那一節自己記著的三次語料錯，
 * 每一次的錯誤數字都**比正確的大**。這是第四次，同一個方向。
 *
 * ## 修法：先正確配對，再篩長度
 *
 * `[^`]*` 讓每一對反引號自己配到自己，長度在**配對之後**才判。
 *
 * ⚠️ **本函式不做任何內容篩選**——`[;{]`／`int main`／排除清單留在各呼叫端，
 * 因為那是「這一支要什麼語料」的問題，各家不同。這裡只負責**切得對**。
 */

/** 撈出所有成對反引號之間的內容，並篩掉過短／過長的。 */
export function backtickSpans(src: string, min = 4, max = 400): string[] {
  const out: string[] = []
  for (const m of src.matchAll(/`([^`]*)`/g)) {
    const c = m[1]
    if (c.length < min || c.length > max) continue
    out.push(c)
  }
  return out
}
