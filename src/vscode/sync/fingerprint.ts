/**
 * 文字指紋——**用來問「我們兩邊講的是同一份文字嗎」**。
 *
 * ## 🔴 為什麼需要它
 *
 * 積木那一側是**樂觀更新**：算出一段範圍編輯、送出去、然後**假設宿主會照做**，
 * 先把本地鏡像改掉。⚠️ 而那個假設只要錯一次，之後每一段範圍都是**錯位**的
 * ——症狀是使用者的檔案被寫成
 *
 * ```cpp
 * }
 * void loop() {
 *   int x;
 * }
 * void loop() {          ← 重複、錯位、少了開頭
 * ```
 *
 * 2026-08-18 使用者在 Arduino IDE 實測到的正是這個形狀。
 *
 * > **樂觀更新沒有對帳的話，第一次分歧不會出聲，
 * > 而它之後的每一次操作都會把檔案弄得更爛。**
 *
 * ## ⚠️ 而版本號**不夠**
 *
 * 版本號答得出「有沒有人動過」，答不出「你以為的內容跟我的一樣嗎」。
 * 兩邊各自算一次指紋才問得出後者。
 *
 * ## 為什麼不是 length
 *
 * 長度相同而內容不同太容易發生（換一行的位置就是）。
 * 🔴 而這裡要的是「不一樣時**一定**測得出來」，不是「大部分時候測得出來」。
 *
 * FNV-1a 32 位元——⚠️ **不是密碼學雜湊**，它只用來偵測**意外**的分歧。
 */
export function textFingerprint(text: string): number {
  let h = 0x811c9dc5
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i)
    // FNV prime 16777619，用位移避免大數乘法溢位
    h = (h + ((h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24))) >>> 0
  }
  return h >>> 0
}
