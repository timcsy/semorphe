/**
 * Python 套件的**命名詞彙補充**。
 *
 * ## 為什麼是「補充」而不是一整份
 *
 * `core/naming.ts` 的分工是「核心給機制（拆名字的演算法），套件給資料」，
 * 而那份資料**不是每個語言各一整套**：
 *
 * ```
 * 操作詞    🔴 共用 —— 「同一個操作在任何主體上用同一個字」
 *                     Python 用 append、C++ 也用 append，那是刻意的
 * 主體      各語言補自己的型別（Python 的 tuple、C++ 的 vector）
 * 單字名    各語言補自己的語言構造（Python 的 import、C++ 的 sizeof）
 * ```
 *
 * ⚠️ **在此之前只有 C++ 那一份，而護欄把它套用在所有語言上**——
 * 於是第二個語言的每一顆元件都要用 C++ 的詞彙表達自己。
 * 那是「全域單槽」的又一個實例（`history/119`）：
 * 一份宣稱通用的清單，在只有一個語言的時候與一份寫死的清單行為完全相同。
 *
 * 🟢 而**操作詞刻意仍然共用**：那不是疏漏，是那份詞彙表存在的理由
 * ——它要讓 `append` 在兩個語言裡是同一件事。
 */

